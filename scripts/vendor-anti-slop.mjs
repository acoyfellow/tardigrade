import { execFileSync } from "node:child_process";
import { cpSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";

const REPOSITORY = "https://github.com/dmmulroy/anti-slop";

const COMMIT = "c44ef22ca116d0ba62a3ff663a0bd13a3f3fa40b";

const SOURCE = "skills/install-anti-slop/assets/anti-slop";

const DESTINATION = new URL("../tools/oxlint/anti-slop/", import.meta.url).pathname;

const banner = `// @generated by scripts/vendor-anti-slop.mjs from ${REPOSITORY} at ${COMMIT}. Do not edit; rerun the script.\n`;

const filesUnder = (directory) =>
	readdirSync(directory).flatMap((name) => {
		const path = join(directory, name);

		return statSync(path).isDirectory() ? filesUnder(path) : [path];
	});

const checkout = mkdtempSync(join(tmpdir(), "anti-slop-"));

try {
	execFileSync("git", ["init", "-q", checkout]);
	execFileSync("git", ["-C", checkout, "fetch", "-q", "--depth", "1", REPOSITORY, COMMIT]);
	execFileSync("git", ["-C", checkout, "checkout", "-q", "FETCH_HEAD"]);
	rmSync(DESTINATION, { recursive: true, force: true });
	cpSync(join(checkout, SOURCE), DESTINATION, { recursive: true });

	for (const file of filesUnder(DESTINATION).filter((path) => path.endsWith(".ts"))) {
		writeFileSync(file, banner + readFileSync(file, "utf8"));
	}

	const installed = filesUnder(DESTINATION).map((path) => relative(DESTINATION, path)).sort();

	writeFileSync(
		join(DESTINATION, "UPSTREAM.md"),
		[
			"# anti-slop (vendored)",
			"",
			`- Source: ${REPOSITORY}`,
			`- Commit: ${COMMIT}`,
			`- Path: \`${SOURCE}\``,
			"- Produced by `scripts/vendor-anti-slop.mjs`. Change rules there or upstream, then rerun it.",
			"- Deviation: each TypeScript file gets a one-line `@generated` banner. No rule logic is changed.",
			"",
			"## Files",
			"",
			...installed.map((path) => `- \`${path}\``),
			"",
		].join("\n"),
	);
	console.log(`vendored ${installed.length} files from ${COMMIT.slice(0, 7)}`);
} finally {
	rmSync(checkout, { recursive: true, force: true });
}
