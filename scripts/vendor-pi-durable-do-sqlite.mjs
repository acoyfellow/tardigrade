import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";

const REPOSITORY = "earendil-works/pi";

const COMMIT = "da866ada1";

const SOURCE = "packages/durable/src/storage/sqlite/cloudflare.ts";

const DESTINATION = new URL("../worker/vendor/", import.meta.url).pathname;

const source = execFileSync("gh", ["api", `repos/${REPOSITORY}/contents/${SOURCE}?ref=${COMMIT}`, "--jq", ".content"], { encoding: "utf8" });

const body = Buffer.from(source, "base64")
	.toString("utf8")
	.replace('from "./database.ts"', 'from "@earendil-works/pi-durable/storage/sqlite"')
	.replace('from "./storage.ts"', 'from "@earendil-works/pi-durable/storage/sqlite"');

const banner = [
	`// @generated by scripts/vendor-pi-durable-do-sqlite.mjs from https://github.com/${REPOSITORY}/blob/${COMMIT}/${SOURCE} (MIT, Earendil Works).`,
	"// Delete this file and import @earendil-works/pi-durable/storage/sqlite/cloudflare once a release ships it.",
	"",
].join("\n");

mkdirSync(DESTINATION, { recursive: true });

writeFileSync(`${DESTINATION}pi-durable-do-sqlite.ts`, banner + body);

console.log(`vendored ${SOURCE} at ${COMMIT}`);
